package com.smartdroneinspection.inspections.api.dto.response;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

public record InspectionResponse(
    UUID id,
    UUID ownerCustomerId,
    UUID assetId,
    String assetName,
    String locationText,
    BigDecimal assetLatitude,
    BigDecimal assetLongitude,
    List<String> inspectionItems,
    UUID inspectorId,
    String inspectorName,
    UUID droneId,
    String droneSerialNumber,
    String droneModel,
    String droneServiceability,
    String flightPermitFileKey,
    String flightPermitFileName,
    Instant plannedStartAt,
    Instant plannedEndAt,
    String status,
    Instant createdAt,
    Instant updatedAt,
    String inspectionType,
    UUID sourceInspectionId,
    boolean reassignmentRequired,
    String declineReason,
    Instant declinedAt,
    UUID declinedByInspectorId,
    String cancellationReason,
    Instant overdueNotifiedAt,
    int clarificationCount,
    String assignmentStatus,
    Instant assignmentAcceptedAt,
    String flightPermitNumber,
    String flightPermitAuthority,
    Instant flightPermitValidFrom,
    Instant flightPermitValidTo,
    String flightPermitDroneSerial,
    Integer flightPermitMaxAltitudeM,
    String flightPermitFileSha256,
    Long flightPermitFileSizeBytes,
    String flightPermitContentType,
    Instant flightPermitUploadedAt,
    UUID flightPermitUploadedBy,
    String flightPermitVerificationStatus,
    UUID flightPermitVerifiedBy,
    String flightPermitVerifiedByName,
    Instant flightPermitVerifiedAt,
    String flightPermitRejectionReason,
    String flightPermitReviewNotes,
    String ownerCustomerName,
    String managerName) {

  public InspectionResponse {
    inspectionItems = inspectionItems == null ? List.of() : List.copyOf(inspectionItems);
  }

  public InspectionResponse(
      UUID id,
      UUID ownerCustomerId,
      UUID assetId,
      String assetName,
      String locationText,
      BigDecimal assetLatitude,
      BigDecimal assetLongitude,
      List<String> inspectionItems,
      UUID inspectorId,
      String inspectorName,
      UUID droneId,
      String droneSerialNumber,
      String droneModel,
      String droneServiceability,
      String flightPermitFileKey,
      String flightPermitFileName,
      Instant plannedStartAt,
      Instant plannedEndAt,
      String status,
      Instant createdAt,
      Instant updatedAt,
      String inspectionType,
      UUID sourceInspectionId,
      boolean reassignmentRequired,
      String declineReason,
      Instant declinedAt,
      UUID declinedByInspectorId,
      String cancellationReason,
      Instant overdueNotifiedAt,
      int clarificationCount,
      String assignmentStatus,
      Instant assignmentAcceptedAt) {
    this(
        id,
        ownerCustomerId,
        assetId,
        assetName,
        locationText,
        assetLatitude,
        assetLongitude,
        inspectionItems,
        inspectorId,
        inspectorName,
        droneId,
        droneSerialNumber,
        droneModel,
        droneServiceability,
        flightPermitFileKey,
        flightPermitFileName,
        plannedStartAt,
        plannedEndAt,
        status,
        createdAt,
        updatedAt,
        inspectionType,
        sourceInspectionId,
        reassignmentRequired,
        declineReason,
        declinedAt,
        declinedByInspectorId,
        cancellationReason,
        overdueNotifiedAt,
        clarificationCount,
        assignmentStatus,
        assignmentAcceptedAt,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        flightPermitFileKey != null && !flightPermitFileKey.isBlank()
            ? "PENDING_REVIEW"
            : "NOT_UPLOADED",
        null,
        null,
        null,
        null,
        null,
        null,
        null);
  }

  public InspectionResponse(
      UUID id,
      UUID ownerCustomerId,
      UUID assetId,
      String assetName,
      String locationText,
      BigDecimal assetLatitude,
      BigDecimal assetLongitude,
      List<String> inspectionItems,
      UUID inspectorId,
      String inspectorName,
      UUID droneId,
      String droneSerialNumber,
      String droneModel,
      String droneServiceability,
      String flightPermitFileKey,
      String flightPermitFileName,
      Instant plannedStartAt,
      Instant plannedEndAt,
      String status,
      Instant createdAt,
      Instant updatedAt,
      String inspectionType,
      UUID sourceInspectionId) {
    this(
        id,
        ownerCustomerId,
        assetId,
        assetName,
        locationText,
        assetLatitude,
        assetLongitude,
        inspectionItems,
        inspectorId,
        inspectorName,
        droneId,
        droneSerialNumber,
        droneModel,
        droneServiceability,
        flightPermitFileKey,
        flightPermitFileName,
        plannedStartAt,
        plannedEndAt,
        status,
        createdAt,
        updatedAt,
        inspectionType,
        sourceInspectionId,
        false,
        null,
        null,
        null,
        null,
        null,
        0,
        "ACCEPTED",
        null);
  }

  public InspectionResponse(
      UUID id,
      UUID ownerCustomerId,
      UUID assetId,
      String assetName,
      String locationText,
      List<String> inspectionItems,
      UUID inspectorId,
      String inspectorName,
      UUID droneId,
      String droneSerialNumber,
      String droneModel,
      String droneServiceability,
      String flightPermitFileKey,
      String flightPermitFileName,
      Instant plannedStartAt,
      Instant plannedEndAt,
      String status,
      Instant createdAt,
      Instant updatedAt) {
    this(
        id,
        ownerCustomerId,
        assetId,
        assetName,
        locationText,
        null,
        null,
        inspectionItems,
        inspectorId,
        inspectorName,
        droneId,
        droneSerialNumber,
        droneModel,
        droneServiceability,
        flightPermitFileKey,
        flightPermitFileName,
        plannedStartAt,
        plannedEndAt,
        status,
        createdAt,
        updatedAt,
        "INITIAL",
        null);
  }

  public static InspectionResponse from(
      com.smartdroneinspection.inspections.domain.Inspection inspection) {
    return new InspectionResponse(
        inspection.getId(),
        inspection.getOwnerCustomerId(),
        inspection.getAssetId(),
        null,
        null,
        null,
        null,
        List.of(),
        inspection.getInspectorId(),
        null,
        inspection.getDroneId(),
        null,
        null,
        null,
        inspection.getFlightPermitFileKey(),
        inspection.getFlightPermitFileName(),
        inspection.getPlannedStartAt(),
        inspection.getPlannedEndAt(),
        inspection.getStatus().name(),
        inspection.getCreatedAt(),
        inspection.getUpdatedAt(),
        inspection.getInspectionType() != null ? inspection.getInspectionType().name() : "INITIAL",
        inspection.getSourceInspectionId(),
        inspection.isReassignmentRequired(),
        inspection.getDeclineReason(),
        inspection.getDeclinedAt(),
        inspection.getDeclinedByInspectorId(),
        inspection.getCancellationReason(),
        inspection.getOverdueNotifiedAt(),
        inspection.getClarificationCount(),
        inspection.getAssignmentStatus() != null
            ? inspection.getAssignmentStatus().name()
            : "ACCEPTED",
        inspection.getAssignmentAcceptedAt(),
        inspection.getFlightPermitNumber(),
        inspection.getFlightPermitAuthority(),
        inspection.getFlightPermitValidFrom(),
        inspection.getFlightPermitValidTo(),
        inspection.getFlightPermitDroneSerial(),
        inspection.getFlightPermitMaxAltitudeM(),
        inspection.getFlightPermitFileSha256(),
        inspection.getFlightPermitFileSizeBytes(),
        inspection.getFlightPermitContentType(),
        inspection.getFlightPermitUploadedAt(),
        inspection.getFlightPermitUploadedBy(),
        inspection.getFlightPermitVerificationStatus().name(),
        inspection.getFlightPermitVerifiedBy(),
        null,
        inspection.getFlightPermitVerifiedAt(),
        inspection.getFlightPermitRejectionReason(),
        inspection.getFlightPermitReviewNotes(),
        null,
        null);
  }
}
